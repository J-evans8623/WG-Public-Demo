 queueNotebookIntegration: (notebookId: string) => void;
 getSessionsForWeek : (anchorDate: Date) => StudySession[];
 removeNotebook: (notebookId: string) => void;
 hasUnseenUpdates: boolean;
 resetUnseenCount: () => void;
