/**
 * @file CalendarDefinitions.ts
 * @description
 *   Updated centralized type definitions for the calendar planner system within BloomMap. This file serves as the
 *   single source of truth for all calendar-related data structures including atomic lesson units, notebook
 *   metadata, study sessions, and scheduling configurations. The definitions now support the new calendar layout
 *   featuring 30/31 day calendar display with multiple study sessions per day and configurable subject distribution.
 *   The atomic design approach ensures lightweight data structures that minimize storage overhead while providing
 *   maximum scheduling flexibility. All types support the spaced repetition learning methodology and multi-notebook
 *   study planning with enhanced session grouping capabilities for better daily study organization.
 */

import type { ScheduleConfig, DayOfWeek } from '@/app/workspace/(studygraph)/components/layout/Calendar/study-planner/models/Configuration.ts';

/**
 * Atomic lesson unit representing a single primary subtopic from a concept map.
 * This is the fundamental scheduling unit for the calendar system, containing
 * minimal metadata required to generate study sessions across multiple notebooks.
 */
export interface LessonUnit {
  /** Display title of the primary concept node */
  conceptNodeTitle: string;
  /** Unique identifier of the primary concept node within its map */
  primaryConceptNodeID: string;
  /** Title of the parent lesson containing this unit */
  parentTitle: string;
  /** Concept map identifier where this lesson unit originates */
  mapID: string;
  LessonOrder:number;
}

/**
 * Comprehensive metadata for a notebook file including lesson units and versioning.
 * This interface enables efficient calendar loading by storing pre-extracted lesson
 * units without requiring full document parsing for schedule generation.
 */
export interface NotebookMeta {
  /** Unique file identifier in the storage system */
  fileId: string;
  /** Firebase storage path for the notebook file */
  filePath: string;
  /** User-friendly display name for the notebook */
  fileName: string;
  /** Array of atomic lesson units extracted from the notebook */
  lessonUnits: LessonUnit[];
  /** Timestamp of last metadata update for cache invalidation */
  lastUpdated: Date;
  /** Version hash for detecting stale metadata */
  version: string;
  /** Color code for visual distinction in calendar */
  colorCode: string;
}

/**
 * Lightweight summary of notebook information for selection interfaces.
 * Used in calendar modals to display available notebooks without loading
 * full metadata until notebook is selected for scheduling.
 */
export interface NotebookSummary {
  /** Unique file identifier */
  fileId: string;
  /** Display name of the notebook */
  fileName: string;
  /** Total number of lesson units available for scheduling */
  totalUnits: number;
  /** Last modification timestamp for sorting and display */
  lastUpdated: Date;
  /** Color code for visual distinction */
  colorCode: string;
}

/**
 * Individual study session generated by the calendar scheduling algorithm.
 * Contains all information needed to launch and display study sessions
 * including target lesson units, session type, and calculated metadata.
 */
export interface StudySession {
  /** Unique identifier for the study session */
  id: string;
  /** Scheduled date and time for the session */
  date: Date;
  /** Complete notebook metadata for file loading */
  notebookMeta: NotebookMeta;
  /** Specific lesson units targeted in this session */
  targetLessonUnits: LessonUnit[];
  /** Type of study session determining content generation strategy */
  type: 'block' | 'revision-block' | 'revision-interleaved';
  /** Configuration parameters for session generation */
  sessionConfig: {
    /** Number of lesson units included in this session default 3 */
    unitCount: number;
  };
  /** Calculated display and estimation metadata */
  metadata: {
    /** Human-readable session title for display */
    sessionTitle: string;
    /** Estimated duration in minutes */
    estimatedDuration: number;
    /** Array of topic titles for quick reference */
    topicTitles: string[];
  };
  /** Optional time slot for daily scheduling */
  timeSlot?: 'morning' | 'afternoon' | 'evening';
}



/**
 * Daily study plan containing all sessions scheduled for a specific date.
 * Organizes multiple study sessions by subject and provides daily overview
 * information for calendar display and user planning.
 */
export interface DailyStudyPlan {
  /** Date for this daily plan */
  date: Date;
  /** All study sessions scheduled for this date */
  sessions: StudySession[];
  /** Subject distribution summary for this day */
  subjectSummary: {
    [notebookId: string]: {
      notebookName: string;
      sessionCount: number;
      totalUnits: number;
      colorCode: string;
    };
  };
  /** Total estimated study time for the day in minutes */
  totalDuration: number;
  /** Completion status tracking */
  completedSessions: string[];
}

/**
 * Calendar month view data structure for 30/31 day calendar display.
 * Contains all daily plans for the month with navigation and summary
 * information for comprehensive calendar visualization.
 */
export interface CalendarMonth {
  /** Year and month for this calendar view */
  year: number;
  month: number; // 0-11 (JavaScript Date month format)
  /** Array of daily plans for each day in the month */
  dailyPlans: DailyStudyPlan[];
  /** Monthly summary statistics */
  monthlySummary: {
    totalSessions: number;
    totalStudyTime: number;
    activeNotebooks: string[];
    completionRate: number;
  };
}

export interface NotebookVersionState {
  notebookId: string;
  trackedVersion: string;
  currentVersion?: string;
  needsUpdate: boolean;
  lastChecked: Date;
}



