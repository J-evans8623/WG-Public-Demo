/**
 * @file app/src/utils/citationSanitizer.ts
 * @description
 * Provides utility functions to validate, normalize, and prune AI-generated citation formats.
 * LLMs occasionally output compound citations (e.g., "<<1, 2>>") or hallucinate indices that
 * do not exist in the provided source list. This utility atomizes compound tags and removes
 * "ghost" references that lack backing data to ensure the frontend only receives renderable tags.
 */

import { Citation } from "@/app/src/schemas/lessonSchema";

/**
 * Scans text for citation tags, atomizes compound formats, and removes orphaned indices.
 * * Logic:
 * 1. Identify patterns like `<<1, 2>>`.
 * 2. Split into individual indices [1, 2].
 * 3. Validate each index against the `validCitations` array.
 * 4. Filter out any index not found in the valid list.
 * 5. Reconstruct the string with only valid, atomic tags (e.g., `<<1>> <<2>>`).
 * 6. If no indices remain valid, remove the tag entirely.
 * * @param text - The raw lecture note string from the AI.
 * @param validCitations - The array of actual Citation objects generated by the AI (Source of Truth).
 * @returns The sanitized string with corrected and validated citation formats.
 */
export function sanitizeCitations(text: string, validCitations?: Citation[] | null): string {
  if (!text) return "";

  //console.log(`Before citation sanitizer h8h8 ${JSON.stringify(text)}`)

  // update - 1: Create a lookup Set for O(1) validation of indices.
  // If validCitations is null/undefined, the set is empty, meaning ALL tags will be pruned (safety).
  const validIndices = new Set(validCitations?.map(c => c.index) || []);

  // Regex explanation:
  // <<       : Literal start
  // \s* : Optional whitespace
  // ([\d,\s]+) : Capture group for the content (digits, commas, spaces)
  // \s* : Optional whitespace
  // >>       : Literal end
  // Global flag (g) to catch all instances in the text
  return text.replace(/<<\s*([\d,\s]+)\s*>>/g, (match, innerContent) => {
    // Split by any character that is NOT a digit (comma, space, etc.)
    // Filter(Boolean) removes empty strings resulting from trailing separators
    const rawIndices = innerContent.split(/[^0-9]+/).filter(Boolean);

    // Safety check: if no numbers were found (e.g. "<< , >>"), return original match or empty
    if (rawIndices.length === 0) return "";

    // update - 2: Filter against the whitelist (Ghost detection)
    // Only keep indices that actually exist in the validCitations array
    const validFiltered = rawIndices.filter((i: any) => validIndices.has(Number(i)));

    // update - 3: If all indices in this tag were ghosts, remove the tag entirely
    if (validFiltered.length === 0) return "";

    // Reconstruct as atomic tags joined by a space (e.g. "<<1>> <<2>>")
    return validFiltered.map((i: any) => `<<${i}>>`).join(' ');
  });
}