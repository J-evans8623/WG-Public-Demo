/**
 * aiTextPreprocessing.ts
 *
 * This file implements an independent pipeline for generating text embeddings
 * and structured lesson metadata using the OpenAI API.
 *
 * Responsibilities:
 *  - generateEmbedding: Accepts raw text and returns an embedding vector.
 *  - generateLessonMetadata: Accepts a hierarchical JSON object (representing the lesson module
 *    with its depth-1 and depth-2 subtopics) and uses a Chain-of-Thought (CoT) prompt to generate
 *    structured lesson metadata (a main topic, subtopic titles, and a summary) that conforms to a
 *    predefined JSON schema.
 *
 * Note: Ensure that the environment variable OPENAI_API_KEY is set with your API key.
 */

import OpenAI from 'openai';
import { lessonMetadataJSONSchema } from './utils/lessonMetadataSchema'; // Adjust relative path if necessary

// Initialize the OpenAI client.
const openai = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY,
});

/**
 * Generates an embedding for the given text using the "text-embedding-ada-002" model.
 *
 * @param text - The raw input text.
 * @returns A promise that resolves to an array of numbers representing the embedding.
 */
export async function generateEmbedding(text: string): Promise<number[]> {
  try {
    const response = await openai.embeddings.create({
      model: 'text-embedding-3-small',
      input: text,
    });
    
    // In the new OpenAI API structure, the embedding is directly available.
    const embedding = response.data[0].embedding;
    return embedding;
  } catch (error) {
    console.error("Error in generateEmbedding:", error);
    throw error;
  }
}

/**
 * Generates lesson metadata (a main topic, subtopic titles, and a summary) based on a hierarchical JSON object
 * generated by the Python microservice. The JSON object includes the full text reference and a list of depth‑1 subtopics,
 * each with its aggregated text and optional depth‑2 subtopics.
 *
 * Your tasks:
 * 1. For each depth‑1 subtopic (and its depth‑2 children, if present), read the "aggregated_text" and assign a concise title.
 * 2. Generate an overall main topic title for the lesson module.
 * 3. Create a concise summary that captures the key points from all subtopics.
 *
 * Output must be a valid JSON object strictly following this format (do not include any extra text):
 * {
 *   "topic": "string",        // Main topic title.
 *   "subtopics": [
 *     {
 *       "title": "string",    // Title for the depth‑1 subtopic.
 *       "subtopics": [        // Optional array for nested depth‑2 subtopic titles.
 *          { "title": "string" }
 *       ]
 *     },
 *     ...
 *   ],
 *   "summary": "string"         // A concise summary of the lesson module.
 * }
 *
 * @param lessonModuleOutput - The hierarchical JSON object generated by the Python microservice.
 * @returns A promise that resolves to the structured lesson metadata.
 */
export async function generateLessonMetadata(lessonModuleOutput: any): Promise<any> {
  const prompt = `
You are an expert curriculum designer and you are creating the topics of a concept map. You are given a specific number of depth1nodes that identify the primary topics of the lesson notes that user wants you to focus on. Some of these
topics have nested subtopics (labeled as depth2nodes), while other subtopics do not have nested subtopics and instead have a clear warning message "DO NOT CREATE SUBTOPICS for this topic ". If you see this message "DO NOT CREATE SUBTOPICS for this topic" , this means
that this depth 1 node is a leaf and that you should create subtopics for this specifc topic.

Please review the text from the uploaded user notes :

1. Generate an overall main topic title for the lesson module.
2. Read each subtopic’s content and assign a concise, descriptive title.
3. If the depth1node has the message "This topic has subtopic", then assign a title to each depth2 node that belongs that topic.
4. If the depth1node has the message '"DO NOT CREATE SUBTOPICS for this topic", then do not add nested subtopics for this depth1node.
5. Produce a concise summary that captures the key points from all subtopics.



Here is the hierarchical JSON object:
"""${JSON.stringify(lessonModuleOutput, null, 2)}"""
  `.trim();

  try {
    console.log(`aiTextPreProcessing input ${JSON.stringify(lessonModuleOutput, null, 2)}`);
    const response = await openai.beta.chat.completions.parse({
      model: "gpt-4o-mini", // Replace with your desired model identifier.
      messages: [
        { role: "system", content: "You are a helpful assistant that generates structured lesson metadata." },
        { role: "user", content: prompt }
      ],
      temperature: 0.5,
      max_completion_tokens: 400,
      response_format: {
        type: "json_schema",
        json_schema: {
          name: lessonMetadataJSONSchema.name,
          schema: lessonMetadataJSONSchema.schema,
          strict: lessonMetadataJSONSchema.strict
        }
      }
    });

    console.log(" aiTextPreProcessing output ", JSON.stringify(response, null, 2));   
    return response.choices[0].message.parsed;
  } catch (error) {
    console.error("Error in generateLessonMetadata:", error);
    // Fallback: Return a simple dummy result.
    return {
      topic: `Topic for lesson module...`,
      subtopics: [{ title: 'Subtopic 1', subtopics: [] }, { title: 'Subtopic 2', subtopics: [] }],
      summary: `Summary for lesson module...`
    };
  }
}
