/**
 * @file aiFeedbackService.ts
 * @description
 * This service implements the specialized logic for generating evidence-based assessments within the 
 * Quiz Feedback Pipeline. Its primary responsibility is to coordinate the prompting strategies that 
 * force the LLM to ground its questions in verbatim textual evidence. It acts as a parallel 
 * peer to the standard UnifiedAIService, utilizing multi-step pedagogical instructions that 
 * prioritize 'proof' over 'creative variety.' By isolating this logic, the service ensures that 
 * changes to the feedback prompt—such as adjusting citation verbosity or explanation depth—do 
 * not affect the baseline quiz generator. It consumes the topic mapping dictionaries from Phase 1 
 * and strictly adheres to the feedback schemas defined in this phase. This file is critical for 
 * maintaining SOLID principles, ensuring that the feedback engine has a single, well-defined 
 * responsibility within the educational ecosystem of the application.
 */

import UnifiedAIService from "@/app/src/services/UnifiedAIService";
import { FeedbackMultipleChoiceSchema } from "@/app/src/schemas/feedbackQuizSchema";



export class AiFeedbackService {
  private aiService: UnifiedAIService;

  constructor() {
    // 1. Initialize the shared AI transport layer
    this.aiService = new UnifiedAIService();
  }

  /**
   * generateFeedbackQuiz
   * @description
   * This function orchestrates the generation of a quiz where every question is accompanied 
   * by an explanation and a direct citation. It combines the base quiz prompt with 
   * a specialized 'evidence-first' system instruction and the topic dictionary.
   * @param context - The textbook or lesson text to base the quiz on.
   * @param promptExtension - The ID mapping dictionary generated by the TopicIdMapper.
   * @param questionCount - The number of questions requested by the educator.
   * @returns A promise resolving to a structured quiz response containing feedback metadata.
   */
  public async generateFeedbackQuiz(
    context: string,
    promptExtension: string,
    questionCount: number
  ): Promise<any> {
    // 2. Define the specialized system prompt for the feedback engine
    const systemPrompt = `
      You are an expert pedagogical assistant. Your goal is to create a quiz that aids student remediation.
      INSTRUCTIONS:
      1. For every question, you MUST provide a detailed 'explanation' of the correct answer.
      2. You MUST provide a 'citation' containing a verbatim quote from the provided context as proof.
      3. Use the 'topicKey' provided in the dictionary below to tag each question correctly.
      4. Ground all questions strictly in the provided text.
      ${promptExtension}
    `;

    const userInput = `Generate a ${questionCount}-question multiple choice quiz based on the following text:\n\n${context}`;

    // 3. Execute the structured output call using the feedback-specific schema
    return await this.aiService.generateStructuredOutput(
      { openai: FeedbackMultipleChoiceSchema, gemini: FeedbackMultipleChoiceSchema } as any,
      userInput,
      systemPrompt,
      { model: "gpt-5-mini", modeleffort: "low" }
    );
  }
}